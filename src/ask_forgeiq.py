MODEL_NAME = "gemini-3.8-flash"


# --------------------------------------------------
# 2. PREPARE RETRIEVED PASSAGES
# --------------------------------------------------

def prepare_context(retrieved_chunks):
    """
    Give every retrieved passage a temporary citation ID.

    Example:
        S1 -> maintenance_manual.txt, Section 4
        S2 -> inspection_checklist.txt, Section 4

    The IDs allow us to validate citations without trying
    to interpret free-form source names generated by Gemini.
    """

    context_parts = []
    source_map = {}

    for index, chunk in enumerate(retrieved_chunks, start=1):
        source_id = f"S{index}"

        # Store the original retrieved metadata.
        source_map[source_id] = {
            "source": chunk.get("source", "Unknown source"),
            "document_id": chunk.get("document_id", "Unknown ID"),
            "document_type": chunk.get(
                "document_type",
                "Unknown document type",
            ),
            "revision": chunk.get("revision", "Unknown revision"),
            "section": chunk.get("section", "Unknown section"),
            "chunk_id": chunk.get("chunk_id"),
            "text": chunk.get("text", ""),
        }

        passage = f"""
[{source_id}]
Source: {source_map[source_id]["source"]}
Document ID: {source_map[source_id]["document_id"]}
Document type: {source_map[source_id]["document_type"]}
Revision: {source_map[source_id]["revision"]}
Section: {source_map[source_id]["section"]}

Passage content:
{source_map[source_id]["text"]}
"""

        context_parts.append(passage)

    context = "\n".join(context_parts)

    return context, source_map


# --------------------------------------------------
# 3. PARSE GEMINI'S STRUCTURED RESPONSE
# --------------------------------------------------

def parse_json_response(response_text):
    """
    Parse the JSON returned by Gemini.

    Also handles a response surrounded by Markdown
    code fences, should the model include them.
    """

    if not response_text:
        raise ValueError("Gemini returned an empty response.")

    cleaned_text = response_text.strip()

    # Remove optional Markdown code fences.
    cleaned_text = re.sub(
        r"^```(?:json)?\s*",
        "",
        cleaned_text,
        flags=re.IGNORECASE,
    )

    cleaned_text = re.sub(
        r"\s*```$",
        "",
        cleaned_text,
    )

    result = json.loads(cleaned_text)

    if not isinstance(result, dict):
        raise ValueError(
            "Gemini's response must be a JSON object."
        )

    if not isinstance(result.get("answer"), str):
        raise ValueError(
            "Gemini's JSON response is missing a valid answer."
        )

    if not isinstance(result.get("citations", []), list):
        raise ValueError(
            "Gemini's citations field must be a list."
        )

    if not isinstance(
        result.get("insufficient_information", False),
        bool,
    ):
        raise ValueError(
            "insufficient_information must be true or false."
        )

    return result


# --------------------------------------------------
# 4. VALIDATE STRUCTURED CITATIONS
# --------------------------------------------------

def validate_structured_citations(
    generated_citations,
    source_map,
):
    """
    Validate every citation ID against the passages
    retrieved for the current question.

    Important:
    A valid ID proves that the cited passage was retrieved.
    It does not prove that the passage supports the claim.
    """

    validated_citations = []
    invalid_citations = []

    for citation in generated_citations:
        if not isinstance(citation, dict):
            invalid_citations.append({
                "citation": citation,
                "reason": "Citation must be a JSON object.",
            })
            continue

        source_id = citation.get("source_id")

        if not isinstance(source_id, str):
            invalid_citations.append({
                "citation": citation,
                "reason": "Citation is missing a string source_id.",
            })
            continue

        if source_id not in source_map:
            invalid_citations.append({
                "citation": citation,
                "reason": (
                    f"{source_id} does not correspond to a "
                    "passage retrieved for this question."
                ),
            })
            continue

        # Do not trust Gemini to supply the canonical source name
        # or section. Obtain those directly from retrieved metadata.
        original_source = source_map[source_id]

        validated_citations.append({
            "source_id": source_id,
            "claim": str(citation.get("claim", "")).strip(),
            "source": original_source["source"],
            "document_id": original_source["document_id"],
            "section": original_source["section"],
            "chunk_id": original_source["chunk_id"],
            "valid": True,
            "validation_type": "retrieval_traceability",
        })

    return {
        "citations": validated_citations,
        "invalid_citations": invalid_citations,
        "total_citations": (
            len(validated_citations) + len(invalid_citations)
        ),
        "valid_citations": len(validated_citations),
        "invalid_citation_count": len(invalid_citations),
        "all_valid": (
            len(generated_citations) > 0
            and len(invalid_citations) == 0
            and len(validated_citations) == len(generated_citations)
        ),
    }


