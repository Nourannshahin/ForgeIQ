# 6. INTERACTIVE TERMINAL APPLICATION
# --------------------------------------------------

def main():
    if not API_KEY:
        raise ValueError(
            "GEMINI_API_KEY was not found. Check your .env file."
        )

    print("Loading ForgeIQ's existing vector database...")

    model, collection = load_vector_store()

    client = genai.Client(api_key=API_KEY)

    print(f"Loaded {collection.count()} indexed chunks.")
    print("\nForgeIQ is ready!")
    print("Ask a question about the available documents.")
    print("Type 'exit' to quit.\n")

    while True:
        question = input("You: ").strip()

        if question.lower() in {"exit", "quit"}:
            print("ForgeIQ session ended.")
            break

        if not question:
            print("Please enter a question.\n")
            continue

        try:
            # Step 1: Retrieve relevant passages.
            retrieved_chunks = search_knowledge_base(
                question,
                model,
                collection,
                top_k=3,
            )

            if not retrieved_chunks:
                print("\nForgeIQ: No passages were retrieved.\n")
                continue

            # Step 2: Generate a structured answer.
            result = generate_answer(
                question,
                retrieved_chunks,
                client,
            )

            # Step 3: Display the answer.
            print(f"\nForgeIQ: {result['answer']}\n")

            # Step 4: Display validated citations.
            print("Supporting sources:")

            if result["citations"]:
                for citation in result["citations"]:
                    print(
                        f"- [{citation['source_id']}] "
                        f"{citation['source']} | "
                        f"{citation['section']}"
                    )
            else:
                print("No citations could be validated.")

            # Step 5: Report citation problems.
            invalid = result["invalid_citations"]

            if invalid:
                print("\nCitation warnings:")

                for citation in invalid:
                    print(
                        f"- {citation['reason']}"
                    )

            if result["insufficient_information"]:
                print(
                    "\nEvidence status: The model indicates that "
                    "the available information is insufficient."
                )

            print()

        except Exception as error:
            print(f"\nAn error occurred: {error}\n")


if __name__ == "__main__":
    main()